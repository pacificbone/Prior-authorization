import test from 'node:test';
import assert from 'node:assert/strict';
import {policies,coverageProfiles} from '../shared/catalog.mjs';
import {samples} from '../shared/fixtures.mjs';
import {resolvePolicy,matchingPolicies,applyPolicyPathway,readiness,formularyResult,buildLetter,validatePolicy} from '../shared/domain.mjs';
import {signBedrock} from '../server/sigv4.mjs';
const today='2026-11-06';
test('HMSA commercial/QUEST and Medicare Advantage use different denosumab preferences',()=>{
  const cq=resolvePolicy({payer:'HMSA',line:'Commercial',benefit:'Medical'},'prolia',[],today).policy;
  const ma=resolvePolicy({payer:'HMSA',line:'Medicare Advantage',benefit:'Medical'},'prolia',[],today).policy;
  assert.deepEqual(cq.preferred,['Jubbonti']);assert.deepEqual(ma.preferred,['Bildyos']);
  assert.notEqual(cq.id,ma.id);assert.equal(formularyResult({payer:'HMSA',line:'Commercial',benefit:'Medical'},'prolia',[],today).status,'unknown');
});
test('HMSA OR pathways require only the selected branch, and an unselected/ambiguous branch cannot release',()=>{
  const sample=samples['hmsa-osteoporosis-evenity'];
  const base=resolvePolicy(sample,sample.drugId,[],today).policy;
  const effective=applyPolicyPathway(base,sample.pathwayId,sample.drugId);
  assert.equal(effective.criteria.length,6);assert.equal(readiness(sample,base,[],today).ready,true);
  assert.equal(readiness({...sample,pathwayId:''},base,[],today).ready,false);
  assert.ok(readiness({...sample,pathwayId:'dexa-ambiguous'},base,[],today).issues.some(s=>s.includes('clarification')));
  assert.match(buildLetter(sample,effective,{today}),/Selected qualifying pathway: C.1.e/);
});
test('HMSA nonpreferred-product exceptions are conditional on the requested drug',()=>{
  const cq=policies.find(p=>p.id==='hmsa-denosumab-cq-2026-04');
  assert.ok(applyPolicyPathway(cq,'fragility-fracture','prolia').criteria.some(c=>c.id==='product-exception'));
  assert.ok(!applyPolicyPathway(cq,'fragility-fracture','jubbonti').criteria.some(c=>c.id==='product-exception'));
  const ma=policies.find(p=>p.id==='hmsa-denosumab-ma-2026-10');
  assert.ok(!applyPolicyPathway(ma,'','bildyos').criteria.some(c=>c.id==='product-exception'));
  assert.ok(applyPolicyPathway(ma,'','jubbonti').criteria.some(c=>c.id==='product-exception'));
  // Re-applying a materialized policy must not duplicate criteria.
  const once=applyPolicyPathway(cq,'fragility-fracture','prolia');assert.equal(applyPolicyPathway(once,'fragility-fracture','prolia').criteria.length,once.criteria.length);
});
test('HMAA published pharmacy tier/exclusion is isolated from medical benefits and other lists',()=>{
  const scope={payer:'HMAA',line:'Commercial',benefit:'Pharmacy',planCode:'HMAA-OPTUMRX-PREMIUM-2026-H2'};
  assert.equal(formularyResult(scope,'prolia',[],today).status,'excluded');
  assert.equal(formularyResult(scope,'stoboclo',[],today).entry.tier,'2');
  assert.equal(formularyResult(scope,'alendronate',[],today).entry.tier,'1');
  assert.equal(formularyResult({...scope,benefit:'Medical'},'prolia',[],today).status,'unknown');
  assert.equal(formularyResult({...scope,planCode:''},'prolia',[],today).status,'unknown');
  assert.equal(formularyResult({...scope,payer:'HMA'},'prolia',[],today).status,'unknown');
  assert.equal(formularyResult(scope,'prolia',[],'2027-01-01').status,'unknown');
});
test('MDX UHC MA authorization list requires the underlying carrier and never acts as clinical criteria',()=>{
  const scope={payer:'MDX',carrier:'UnitedHealthcare',line:'Medicare Advantage',benefit:'Medical'};
  assert.equal(matchingPolicies(scope,'evenity',[],today).length,1);
  assert.equal(resolvePolicy(scope,'evenity',[],today).policy,null);
  assert.equal(formularyResult(scope,'evenity',[],today).status,'unknown');
  for(const change of [{carrier:''},{carrier:'Humana'},{line:'Commercial'},{benefit:'Pharmacy'}])assert.equal(matchingPolicies({...scope,...change},'evenity',[],today).length,0);
});
test('HMA and MDX source imports require an underlying plan; HMA additionally requires the exact group/list',()=>{
  assert.equal(coverageProfiles.HMA.requiresCarrier,true);assert.equal(coverageProfiles.MDX.requiresCarrier,true);
  const p={...policies[0],id:'custom-hma-rule',payer:'HMA'};
  assert.throws(()=>validatePolicy(p,today));
  assert.throws(()=>validatePolicy({...p,carrier:'Self-funded / employer plan'},today));
  assert.equal(validatePolicy({...p,carrier:'Self-funded / employer plan',planCode:'EXACT-GROUP'},today).planCode,'EXACT-GROUP');
});
